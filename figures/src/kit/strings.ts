export function t(lang: Lang, key: StringKey): string {
  return STRINGS[lang][key];
}

/** A colon in the language's typography: « source : » in French, "source:" in English. */
export function colon(lang: Lang): string {
  return lang === 'fr' ? ' :' : ':';
}
